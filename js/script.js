const zoneImages = document.querySelectorAll(".logic__img-photo");
let currentIndex = 0;

const btnUp = document.querySelector(".logic__button-up");
const btnDown = document.querySelector(".logic__button-down");

const textTitle1 = document.querySelector(".logic__title");
const textLabel1 = document.querySelector(".logic__label-1");
const textLabel2 = document.querySelector(".logic__label-2");
const textLabel3 = document.querySelector(".logic__label-3");

function updateZone(index) {
  zoneImages.forEach((img) => img.classList.remove("is-active"));
  zoneImages[index].classList.add("is-active");

  textTitle1.textContent = zones[index].title;
  textLabel1.textContent = zones[index].facts[0];
  textLabel2.textContent = zones[index].facts[1];
  textLabel3.textContent = zones[index].facts[2];

  currentIndex = index;
}

btnUp.addEventListener("click", () => {
  const nextIndex = (currentIndex + 1) % zoneImages.length;
  updateZone(nextIndex);
});

btnDown.addEventListener("click", () => {
  const prevIndex = (currentIndex - 1 + zoneImages.length) % zoneImages.length;
  updateZone(prevIndex);
});
